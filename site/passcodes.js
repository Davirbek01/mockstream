// Validate premium passcode with candidate name
// User enters ONLY the code part (e.g., "E8AH-OF3V"), system silently combines with name
// Stored format: nameXXXX-XXXX (e.g., "DavirbekE8AH-OF3V")
// Returns { valid: true/false, error: string (if invalid) }
// IGNORES HYPHENS - user can enter code with or without hyphens
window.validatePremiumPasscode = function(candidateName, codeOnly) {
  if (!candidateName || !codeOnly) {
    return { valid: false, error: 'Please enter both name and access code.' };
  }
  
  // Extract first name (first word) - used for combining with code
  const cleanName = candidateName.trim().toLowerCase();
  const firstName = cleanName.split(/\s+/)[0];
  
  // Remove ALL hyphens and spaces from code, then lowercase
  const cleanCode = codeOnly.trim().toLowerCase().replace(/[-\s]/g, '');
  
  // Silently combine name + code to create full passcode
  const combinedWithFirstName = firstName + cleanCode;
  
  // Try with full name (no spaces) as fallback
  const nameNoSpaces = cleanName.replace(/\s+/g, '');
  const combinedWithFullName = nameNoSpaces + cleanCode;
  
  // Check if combined code matches any premium passcode (also remove hyphens from stored codes)
  const matchingCode = window.PREMIUM_PASSCODES.find(code => {
    const codeLower = code.toLowerCase().replace(/[-\s]/g, '');
    return codeLower === combinedWithFirstName || codeLower === combinedWithFullName;
  });
  
  if (matchingCode) {
    return { valid: true, matchedCode: matchingCode };
  }
  
  // No match found - return generic error (don't reveal the combination logic)
  return { valid: false, error: 'Invalid access code. Please check and try again.' };
};

// Legacy function - kept for backward compatibility
window.validatePasscode = function(combinedKey) {
  if (!combinedKey) return false;
  const cleanKey = combinedKey.trim().toLowerCase();
  
  // Check if any passcode matches (passcodes stored in lowercase)
  return window.PREMIUM_PASSCODES.some(code => code.toLowerCase() === cleanKey);
};

window.isPremiumUnlocked = function() {
  // Check session access (from passcodes.js name+code) OR temporary access (from backend one-time code)
  // Using sessionStorage - requires re-entry each session (no caching for security)
  return sessionStorage.getItem('premiumUnlocked') === 'true' || sessionStorage.getItem('tempPremiumAccess') === 'true';
};

window.getPremiumUserName = function() {
  // Using sessionStorage - session-only, requires re-entry each session
  return sessionStorage.getItem('premiumUserName') || '';
};

window.getUsedPasscode = function() {
  // Using sessionStorage - session-only, requires re-entry each session
  return sessionStorage.getItem('usedPasscode');
};

window.unlockPremium = function(candidateName, passcode) {
  const validation = window.validatePremiumPasscode(candidateName, passcode);
  if (validation.valid) {
    // Using sessionStorage - session-only access, requires re-entry each session (more secure)
    // AI score codes are stored separately in localStorage to prevent reuse
    sessionStorage.setItem('premiumUnlocked', 'true');
    sessionStorage.setItem('premiumUserName', candidateName.trim());
    sessionStorage.setItem('usedPasscode', passcode.trim().toLowerCase());
    return true;
  }
  return false;
};

// Check if user has premium access and optionally verify name matches
window.checkPremiumAccess = function(candidateName) {
  if (!window.isPremiumUnlocked()) {
    return { valid: false, reason: 'not_unlocked' };
  }
  
  // If name is provided, verify it matches the stored premium user EXACTLY
  if (candidateName) {
    const storedName = (window.getPremiumUserName() || '').trim().toLowerCase();
    const checkName = candidateName.trim().toLowerCase();
    
    // Require EXACT match - no partial names allowed
    if (storedName && storedName !== checkName) {
      console.log('Premium name mismatch! Stored:', storedName, 'Entered:', checkName);
      return { valid: false, reason: 'name_mismatch', storedName: window.getPremiumUserName() };
    }
  }
  
  return { valid: true };
};

// Check if a code matches any premium passcode (with ANY name)
// Returns the owner's first name if found, null if not a premium code
window.findPremiumCodeOwner = function(codeOnly) {
  if (!codeOnly) return null;
  
  // Remove ALL hyphens and spaces from entered code, then lowercase
  const cleanCode = codeOnly.trim().toLowerCase().replace(/[-\s]/g, '');
  
  // Check each premium passcode to see if the code part matches
  for (const passcode of window.PREMIUM_PASSCODES) {
    const passcodeLower = passcode.toLowerCase().replace(/[-\s]/g, '');
    // Premium codes are format: nameXXXXXXXX (name + 8 alphanumeric chars)
    // The code part is the last 8 characters (without hyphens)
    if (passcodeLower.endsWith(cleanCode) && cleanCode.length >= 6) {
      // Found a match - extract the name part (everything before the code)
      const nameLength = passcodeLower.length - cleanCode.length;
      if (nameLength > 0) {
        // Return true (we found a match) but don't reveal the name
        return true;
      }
    }
  }
  
  return null;
};
